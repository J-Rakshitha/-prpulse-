def feature_columns_for_stage(stage: str) -> list[str]:
    if stage == "A":
        return list(FEATURE_COLUMNS_A)
    return list(FEATURE_COLUMNS_A) + list(FEATURE_COLUMNS_EARLY)


def parse_ts(value: str | None) -> datetime | None:
    if not value:
        return None
    return datetime.strptime(value, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)


