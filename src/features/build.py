def _load_train_prs(conn: sqlite3.Connection) -> pd.DataFrame:
    ph = ",".join("?" for _ in TRAIN_REPOS)
    return pd.read_sql_query(
        f"""
        SELECT p.*, r.full_name AS repo_full_name
        FROM prs p
        JOIN repos r ON r.id = p.repo_id
        WHERE r.full_name IN ({ph}) AND p.ingest_status = 'complete'
        ORDER BY p.created_at
        """,
        conn,
        params=list(TRAIN_REPOS),
    )


def _precompute_file_aggs(conn: sqlite3.Connection, pr_ids: list[int]) -> pd.DataFrame:
    if not pr_ids:
        return pd.DataFrame(
            columns=[
                "pr_id",
                "n_files_approx",
                "additions_approx",
                "deletions_approx",
                "touches_tests",
                "touches_docs",
                "touches_ci_config",
                "touches_deps",
                "touches_auth",
                "touches_migration",
                "docs_only",
                "paths",
            ]
        )
    files = pd.read_sql_query(
        f"SELECT pr_id, path, additions, deletions FROM pr_files WHERE pr_id IN ({','.join('?' for _ in pr_ids)})",
        conn,
        params=pr_ids,
    )
    if files.empty:
        return pd.DataFrame({"pr_id": pr_ids}).assign(
            n_files_approx=0,
            additions_approx=0,
            deletions_approx=0,
            touches_tests=0,
            touches_docs=0,
            touches_ci_config=0,
            touches_deps=0,
            touches_auth=0,
            touches_migration=0,
            docs_only=0,
            paths=[[] for _ in pr_ids],
        )

    def path_flags(paths: list[str]) -> pd.Series:
        return pd.Series(
            {
                "touches_tests": int(any(TEST_RE.search(p or "") for p in paths)),
                "touches_docs": int(any(DOC_RE.search(p or "") for p in paths)),
                "touches_ci_config": int(any(CI_RE.search(p or "") for p in paths)),
                "touches_deps": int(any(DEP_RE.search(p or "") for p in paths)),
                "touches_auth": int(any(AUTH_RE.search(p or "") for p in paths)),
                "touches_migration": int(any(MIG_RE.search(p or "") for p in paths)),
                "docs_only": int(bool(paths) and all(DOC_RE.search(p or "") for p in paths)),
            }
        )

    rows = []
    for pr_id, grp in files.groupby("pr_id"):
        paths = grp["path"].fillna("").tolist()
        flags = path_flags(paths)
        rows.append(
            {
                "pr_id": int(pr_id),
                "n_files_approx": len(paths),
                "additions_approx": int(grp["additions"].fillna(0).sum()),
                "deletions_approx": int(grp["deletions"].fillna(0).sum()),
                "paths": paths,
                **flags.to_dict(),
            }
        )
    return pd.DataFrame(rows)


def _commits_at_open(conn: sqlite3.Connection, prs: pd.DataFrame) -> pd.Series:
    pr_ids = prs["id"].tolist()
    commits = pd.read_sql_query(
        f"SELECT pr_id, committed_at FROM pr_commits WHERE pr_id IN ({','.join('?' for _ in pr_ids)})",
        conn,
        params=pr_ids,
    )
    created = prs.set_index("id")["created_at"]
    if commits.empty:
        return pd.Series(0, index=prs["id"])
    commits = commits.merge(created.rename("created_at"), left_on="pr_id", right_index=True)
    ok = commits["committed_at"].isna() | (commits["committed_at"] <= commits["created_at"])
    counts = commits.loc[ok].groupby("pr_id").size()
    return counts.reindex(prs["id"]).fillna(0).astype(int)


def _first_ci(conn: sqlite3.Connection, pr_ids: list[int]) -> pd.DataFrame:
    ci = pd.read_sql_query(
        f"""
        SELECT pr_id, conclusion, started_at, completed_at
        FROM ci_runs
        WHERE pr_id IN ({','.join('?' for _ in pr_ids)})
          AND completed_at IS NOT NULL
        ORDER BY completed_at
        """,
        conn,
        params=pr_ids,
    )
    if ci.empty:
        return pd.DataFrame(columns=["pr_id", "conclusion", "started_at", "completed_at"])
    return ci.sort_values("completed_at").groupby("pr_id", as_index=False).first()


def _author_features(prs: pd.DataFrame, first_ci: pd.DataFrame) -> pd.DataFrame:
    """Author history strictly before each PR's created_at."""
    work = prs[["id", "repo_id", "author_login", "created_at", "merged_at", "ci_label_available"]].copy()
    work = work.merge(first_ci.rename(columns={"pr_id": "id"}), on="id", how="left")
    t0 = pd.to_datetime(work["created_at"], utc=True)
    tm = pd.to_datetime(work["merged_at"], utc=True)
    work["t0"] = t0
    work["tm"] = tm
    work["merge_hours"] = np.where(tm.notna(), (tm - t0).dt.total_seconds() / 3600.0, np.nan)
    work["ci_fail"] = np.where(
        work["conclusion"].notna() & (work["ci_label_available"] == 1),
        work["conclusion"].isin(FAILURE_CONCLUSIONS).astype(float),
        np.nan,
    )
    work = work.sort_values(["repo_id", "author_login", "created_at", "id"])

    rows: list[dict[str, Any]] = []
    for _, grp in work.groupby(["repo_id", "author_login"], sort=False):
        opened_before: list[Any] = []
        # (merged_at, hours)
        merges: list[tuple[Any, float]] = []
        # (completed_proxy=created_at of prior labeled PR, fail)
        # Use prior PR created_at as order; only count CI when that PR existed before t0.
        ci_pairs: list[tuple[Any, float]] = []
        for _, r in grp.iterrows():
            t0v = r["t0"]
            prior_opened = len(opened_before)
            prior_merged = sum(1 for mt, _ in merges if mt < t0v)
            hours = [h for mt, h in merges if mt < t0v]
            med = float(np.median(hours)) if hours else float("nan")
            ci_vals = [f for ct, f in ci_pairs if ct < t0v]
            fail_rate = float(np.mean(ci_vals)) if ci_vals else float("nan")
            rows.append(
                {
                    "pr_id": int(r["id"]),
                    "prior_opened_count": prior_opened,
                    "prior_merged_count": prior_merged,
                    "prior_merge_rate": (prior_merged / prior_opened) if prior_opened else float("nan"),
                    "first_time_contributor": int(prior_opened == 0),
                    "median_prior_merge_hours": med,
                    "prior_ci_fail_rate": fail_rate,
                }
            )
            opened_before.append(r["id"])
            if pd.notna(r["tm"]):
                merges.append((r["tm"], float(r["merge_hours"])))
            if pd.notna(r["ci_fail"]):
                # CI outcome of this PR becomes knowable after its first completed run;
                # we only expose it to later PRs opened after this PR's created_at
                # (conservative: avoids needing completed_at join in this loop).
                ci_pairs.append((t0v, float(r["ci_fail"])))
    return pd.DataFrame(rows)


def _module_fail_history(prs: pd.DataFrame, file_aggs: pd.DataFrame, first_ci: pd.DataFrame) -> pd.DataFrame:
    """File-history proxy: top-level module fail rate before each PR (fast)."""
    paths = file_aggs[["pr_id", "paths"]].copy()
    paths["module"] = paths["paths"].apply(
        lambda ps: sorted({(p.split("/")[0] if p else "") for p in (ps or [])} - {""})
    )
    exploded = paths.explode("module").dropna(subset=["module"])
    meta = prs[["id", "repo_id", "created_at", "ci_label_available"]].rename(columns={"id": "pr_id"})
    meta = meta.merge(first_ci.rename(columns={"pr_id": "pr_id"}), on="pr_id", how="left")
    meta["fail"] = meta["conclusion"].isin(FAILURE_CONCLUSIONS).astype(float)
    meta.loc[meta["conclusion"].isna() | (meta["ci_label_available"] != 1), "fail"] = np.nan

    hist = exploded.merge(meta, on="pr_id", how="left")
    hist = hist.sort_values(["repo_id", "module", "created_at", "pr_id"])
    hist["prior_fail_rate"] = hist.groupby(["repo_id", "module"])["fail"].transform(
        lambda s: s.shift(1).expanding().mean()
    )
    agg = hist.groupby("pr_id")["prior_fail_rate"].agg(["mean", "max"]).reset_index()
    agg.columns = ["pr_id", "file_hist_fail_mean", "file_hist_fail_max"]
    return agg


def _repo_state_features(prs: pd.DataFrame, events: pd.DataFrame) -> pd.DataFrame:
    """Open PR count, 30d median merge hours, 14d reviewer activity at created_at."""
    rows = []
    prs_sorted = prs.sort_values("created_at")
    for repo_id, grp in prs_sorted.groupby("repo_id"):
        repo_events = events[events["repo_id"] == repo_id]
        created_list = pd.to_datetime(grp["created_at"], utc=True).tolist()
        ids = grp["id"].tolist()
        # Precompute merged PRs for this repo
        merged = grp[grp["merged_at"].notna()].copy()
        merged["mh"] = (
            pd.to_datetime(merged["merged_at"], utc=True) - pd.to_datetime(merged["created_at"], utc=True)
        ).dt.total_seconds() / 3600.0
        merged_at_ns = pd.to_datetime(merged["merged_at"], utc=True).astype("int64").to_numpy()
        mh_vals = merged["mh"].to_numpy()
        closed_at = pd.to_datetime(grp["closed_at"], utc=True)
        created_at = pd.to_datetime(grp["created_at"], utc=True)
        merged_at_all = pd.to_datetime(grp["merged_at"], utc=True)

        rev_times_ns = (
            pd.to_datetime(
                repo_events.loc[repo_events["event_type"] == "review_submitted", "occurred_at"],
                utc=True,
            )
            .astype("int64")
            .sort_values()
            .to_numpy()
        )

        for pr_id, t0 in zip(ids, created_list):
            open_n = int(
                (
                    (created_at < t0)
                    & (merged_at_all.isna() | (merged_at_all >= t0))
                    & (closed_at.isna() | (closed_at >= t0))
                ).sum()
            )
            window_start = t0 - pd.Timedelta(days=30)
            t0_ns = int(t0.value)
            start_ns = int(window_start.value)
            mask = (merged_at_ns < t0_ns) & (merged_at_ns >= start_ns)
            med30 = float(np.median(mh_vals[mask])) if mask.any() else float("nan")
            rev_start_ns = int((t0 - pd.Timedelta(days=14)).value)
            if len(rev_times_ns):
                rev_n = int(
                    np.searchsorted(rev_times_ns, t0_ns, side="left")
                    - np.searchsorted(rev_times_ns, rev_start_ns, side="left")
                )
            else:
                rev_n = 0
            rows.append(
                {
                    "pr_id": pr_id,
                    "open_pr_count_at_t0": open_n,
                    "median_merge_hours_30d": med30,
                    "reviewer_activity_14d": rev_n,
                }
            )
    return pd.DataFrame(rows)


def _early_for_stage(
    prs: pd.DataFrame,
    events: pd.DataFrame,
    ci: pd.DataFrame,
    stage: str,
) -> pd.DataFrame:
    offset = STAGE_OFFSETS[stage]
    rows = []
    events_by_pr = {pid: g for pid, g in events.groupby("pr_id")}
    ci_by_pr = {pid: g for pid, g in ci.groupby("pr_id")}
    for _, row in prs.iterrows():
        pr_id = int(row["id"])
        t0 = parse_ts(row["created_at"])
        assert t0 is not None
        cutoff = t0 + offset
        cutoff_s = to_utc_iso(cutoff)
        created_s = row["created_at"]
        ev = events_by_pr.get(pr_id)
        reviewers: set[str] = set()
        n_comments = 0
        n_sync = 0
        first_comment = None
        review_submitted = 0
        if ev is not None:
            sub = ev[(ev["occurred_at"] >= created_s) & (ev["occurred_at"] <= cutoff_s)]
            for _, e in sub.iterrows():
                et = e["event_type"]
                when = parse_ts(e["occurred_at"])
                if et == "reviewer_assigned" and e["actor_login"]:
                    reviewers.add(e["actor_login"])
                elif et == "comment":
                    n_comments += 1
                    first_comment = first_comment or when
                elif et == "review_submitted":
                    review_submitted = 1
                    if e["actor_login"]:
                        reviewers.add(e["actor_login"])
                    first_comment = first_comment or when
                elif et == "synchronize":
                    n_sync += 1
        ci_sub = ci_by_pr.get(pr_id)
        first_ci_done = None
        ci_failed = 0.0
        if ci_sub is not None:
            done = ci_sub[ci_sub["completed_at"].notna() & (ci_sub["completed_at"] <= cutoff_s)].sort_values(
                "completed_at"
            )
            if len(done):
                first = done.iloc[0]
                first_ci_done = parse_ts(first["completed_at"])
                if first["conclusion"] in FAILURE_CONCLUSIONS:
                    ci_failed = 1.0

        def minutes(ts: datetime | None) -> float:
            if ts is None:
                return float("nan")
            return max(0.0, (ts - t0).total_seconds() / 60.0)

        rows.append(
            {
                "pr_id": pr_id,
                "reviewer_assigned_by_cutoff": 1.0 if reviewers else 0.0,
                "n_reviewers_by_cutoff": float(len(reviewers)),
                "minutes_to_first_comment": minutes(first_comment),
                "minutes_to_first_ci": minutes(first_ci_done),
                "ci_finished_by_cutoff": 1.0 if first_ci_done else 0.0,
                "ci_failed_by_cutoff": ci_failed,
                "review_submitted_by_cutoff": float(review_submitted),
                "n_comments_by_cutoff": float(n_comments),
                "n_synchronize_by_cutoff": float(n_sync),
            }
        )
    return pd.DataFrame(rows)


def _targets(prs: pd.DataFrame, first_ci: pd.DataFrame, cfg: dict[str, Any]) -> pd.DataFrame:
    days = int(cfg["thresholds"]["merged_within_days"])
    now = datetime.now(timezone.utc)
    t0 = pd.to_datetime(prs["created_at"], utc=True)
    tm = pd.to_datetime(prs["merged_at"], utc=True)
    merge_hours = (tm - t0).dt.total_seconds() / 3600.0
    age_days = (pd.Timestamp(now) - t0).dt.total_seconds() / 86400.0
    merged_within = pd.Series(np.nan, index=prs.index)
    resolved_or_old = (age_days >= days) | prs["merged_at"].notna() | (prs["state"] != "open")
    merged_within.loc[resolved_or_old] = (
        prs["merged_at"].notna() & (merge_hours <= days * 24)
    ).astype(float)
    # still open and young → unlabeled
    young_open = (prs["state"] == "open") & (age_days < days)
    merged_within.loc[young_open] = np.nan

    ci = first_ci.set_index("pr_id").reindex(prs["id"].to_numpy())
    labeled = (prs["ci_label_available"].fillna(0).astype(int) == 1).to_numpy()
    ci_failed = np.full(len(prs), np.nan)
    ci_dur = np.full(len(prs), np.nan)
    if "conclusion" in ci.columns:
        conclusions = ci["conclusion"].to_numpy()
        fails = np.array(
            [float(c in FAILURE_CONCLUSIONS) if isinstance(c, str) else np.nan for c in conclusions]
        )
        ci_failed = np.where(labeled, fails, np.nan)
        st = pd.to_datetime(ci["started_at"], utc=True)
        en = pd.to_datetime(ci["completed_at"], utc=True)
        dur = ((en - st).dt.total_seconds() / 60.0).to_numpy()
        ci_dur = np.where(labeled, dur, np.nan)

    return pd.DataFrame(
        {
            "pr_id": prs["id"].values,
            "merge_hours": merge_hours.values,
            "merged_within_7d": merged_within.values,
            "ci_failed_first_run": ci_failed,
            "ci_duration_minutes": ci_dur,
        }
    )


def build_stage_matrix(
    conn: sqlite3.Connection,
    *,
    stage: str,
    cfg: dict[str, Any] | None = None,
    pr_ids: list[int] | None = None,
) -> pd.DataFrame:
    cfg = cfg or load_settings()
    # Always load the full train universe so author/module/repo history stay point-in-time correct
    # when rebuilding a single PR for the PIT test.
    prs_all = _load_train_prs(conn).reset_index(drop=True)
    ids_all = prs_all["id"].tolist()
    logger.info("Building stage %s context for %s PRs", stage, len(prs_all))

    file_aggs = _precompute_file_aggs(conn, ids_all)
    commits = _commits_at_open(conn, prs_all)
    first_ci = _first_ci(conn, ids_all)
    author = _author_features(prs_all, first_ci)
    mod_hist = _module_fail_history(prs_all, file_aggs, first_ci)

    events = pd.read_sql_query(
        f"""
        SELECT e.pr_id, e.event_type, e.occurred_at, e.actor_login, p.repo_id
        FROM pr_events e
        JOIN prs p ON p.id = e.pr_id
        WHERE e.pr_id IN ({','.join('?' for _ in ids_all)})
        """,
        conn,
        params=ids_all,
    )
    ci_all = pd.read_sql_query(
        f"""
        SELECT pr_id, conclusion, started_at, completed_at
        FROM ci_runs WHERE pr_id IN ({','.join('?' for _ in ids_all)})
        """,
        conn,
        params=ids_all,
    )
    repo_state = _repo_state_features(prs_all, events)
    targets = _targets(prs_all, first_ci, cfg)

    t0 = pd.to_datetime(prs_all["created_at"], utc=True)
    base = prs_all[
        ["id", "repo_id", "repo_full_name", "number", "created_at", "is_bot", "state", "ci_label_available", "draft"]
    ].copy()
    base = base.rename(columns={"id": "pr_id"})
    base["stage"] = stage
    base["commits_at_open"] = commits.reindex(prs_all["id"]).fillna(0).astype(int).values
    base = base.merge(file_aggs.drop(columns=["paths"], errors="ignore"), on="pr_id", how="left")
    for col in (
        "n_files_approx",
        "additions_approx",
        "deletions_approx",
        "touches_tests",
        "touches_docs",
        "touches_ci_config",
        "touches_deps",
        "touches_auth",
        "touches_migration",
        "docs_only",
    ):
        if col not in base.columns:
            base[col] = 0
        base[col] = base[col].fillna(0)
    base["log1p_additions_approx"] = np.log1p(base["additions_approx"])
    base["log1p_deletions_approx"] = np.log1p(base["deletions_approx"])
    base["log1p_n_files_approx"] = np.log1p(base["n_files_approx"])
    base = base.merge(author, on="pr_id", how="left")
    base = base.merge(mod_hist, on="pr_id", how="left")
    base = base.merge(repo_state, on="pr_id", how="left")
    base["hour_utc"] = t0.dt.day_of_week.values * 0 + t0.dt.hour.values
    base["weekday"] = t0.dt.day_of_week.values
    base["is_weekend"] = (t0.dt.day_of_week >= 5).astype(int).values
    base["month"] = t0.dt.month.values
    fri_hour = int(cfg["timing"]["friday_evening_start_hour_utc"])
    base["is_friday_evening"] = ((t0.dt.day_of_week == 4) & (t0.dt.hour >= fri_hour)).astype(int).values
    base["repo_is_pandas"] = (base["repo_full_name"] == "pandas-dev/pandas").astype(int)
    base = base.merge(targets, on="pr_id", how="left")

    if stage in ("B", "C"):
        early = _early_for_stage(prs_all, events, ci_all, stage)
        base = base.merge(early, on="pr_id", how="left")

    if pr_ids is not None:
        base = base[base["pr_id"].isin(pr_ids)].copy()

    cols = feature_columns_for_stage(stage)
    assert_feature_columns_allowed(cols)
    missing = [c for c in cols if c not in base.columns]
    if missing:
        raise RuntimeError(f"missing columns: {missing}")
    return base.reset_index(drop=True)


def rebuild_features_for_pr(
    conn: sqlite3.Connection,
    pr_id: int,
    stage: str,
    cfg: dict[str, Any] | None = None,
) -> dict[str, float]:
    """Rebuild one PR's features (used by PIT equality test)."""
    matrix = build_stage_matrix(conn, stage=stage, cfg=cfg, pr_ids=[pr_id])
    cols = feature_columns_for_stage(stage)
    row = matrix.iloc[0]
    return {c: float(row[c]) if pd.notna(row[c]) else float("nan") for c in cols}


